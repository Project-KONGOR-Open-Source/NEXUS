    public required Account Account { get; set; }

    /// <summary>
    ///     Whether the reward tier for the given total mastery level has already been claimed.
    /// </summary>
    public bool HasObtained(int level)
    {
        PropertyInfo? property = GetType().GetProperties().SingleOrDefault(property => property.Name == $"Obtained_{level:D4}");

        return property is not null && Convert.ToBoolean(property.GetValue(this));
    }

    /// <summary>
    ///     Marks the reward tier for the given total mastery level as claimed.
    /// </summary>
    /// <returns>
    ///     <see langword="true"/> if the reward tier exists and was marked as claimed, otherwise <see langword="false"/>.
    /// </returns>
    public bool MarkObtained(int level)
    {
        PropertyInfo? property = GetType().GetProperties().SingleOrDefault(property => property.Name == $"Obtained_{level:D4}");

        if (property is null)
            return false;

        property.SetValue(this, true);

        return true;
    }

