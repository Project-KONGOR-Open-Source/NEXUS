/// <summary>
///     Tracks which total mastery level reward tiers an account has already claimed.
///     There is one flag per reward tier, named "Obtained_" followed by the required total mastery level padded to four digits (for example "Obtained_0015").
///     The reward content for each tier is defined in the mastery rewards configuration. This entity records only whether each tier has been claimed.
/// </summary>
[Index(nameof(AccountID), IsUnique = true)]
